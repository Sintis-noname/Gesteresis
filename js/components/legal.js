const Legal = {
  /**
   * Рендерит юридическую страницу.
   * @param {string} pageKey — ключ из LEGAL_PAGES (privacy, terms, pd, ...)
   */
  render(pageKey) {
    const container = document.getElementById('view-legal');
    if (!container) return;

    const page = LEGAL_PAGES[pageKey];
    if (!page) {
      container.innerHTML = this._renderNotFound(pageKey);
      return;
    }

    container.innerHTML = `
      <!-- Навигация назад -->
      <div class="flex flex-wrap items-center justify-between gap-4 bg-bg-surface border border-border-subtle rounded-card p-5">
        <div class="flex items-center gap-4">
          <a href="#/" class="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold bg-bg-elevated hover:bg-bg-surface text-text-primary border border-border-subtle transition">
            ← Назад к дашборду
          </a>
          <div>
            <h1 class="text-lg sm:text-xl font-bold text-text-primary">${Html.escape(page.title)}</h1>
            <p class="text-xs text-text-secondary font-mono mt-0.5">
              Редакция от ${Html.formatDate(page.updated)}
            </p>
          </div>
        </div>
      </div>

      <!-- Контент -->
      <article class="bg-bg-surface border border-border-subtle rounded-card p-6 sm:p-8 space-y-6">
        ${page.sections.map(sec => `
          <section class="space-y-2">
            <h2 class="text-base sm:text-lg font-bold text-text-primary">${Html.escape(sec.heading)}</h2>
            <p class="text-sm text-text-secondary leading-relaxed whitespace-pre-line">${Html.escape(sec.body)}</p>
          </section>
        `).join('')}
      </article>

      <!-- Плашка «Поддержано Фондом содействия инновациям» -->
      ${page.banner ? `
        <div class="bg-bg-surface border border-[#C9A24A]/60 rounded-card p-6 sm:p-8 flex flex-col items-center text-center gap-4">
          <img
            src="${Html.escape(page.banner.logo)}"
            alt="${Html.escape(page.banner.logoAlt)}"
            class="h-16 sm:h-20 w-auto object-contain"
            loading="lazy"
          />
          <div class="space-y-2 max-w-2xl">
            <h2 class="text-base sm:text-lg font-bold text-[#C9A24A]">
              ${Html.escape(page.banner.heading)}
            </h2>
            <p class="text-sm text-text-secondary leading-relaxed">
              ${Html.escape(page.banner.text)}
            </p>
          </div>
        </div>
      ` : ''}
    `;
  },

  /**
   * @private
   */
  _renderNotFound(pageKey) {
    return `
      <div class="bg-bg-surface border border-border-subtle rounded-card p-8 text-center space-y-4">
        <h2 class="text-lg font-bold text-status-alarm">Страница "${Html.escape(pageKey)}" не найдена</h2>
        <a href="#/" class="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-bg-elevated hover:bg-bg-surface text-sm text-text-primary border border-border-subtle transition">
          ← Назад к дашборду
        </a>
      </div>
    `;
  },
};

window.Legal = Legal;
